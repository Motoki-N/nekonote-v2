-- ========================================

-- シーンレビューの「通す」確定先。draft = 未承認（既定）/ approved = 承認済み
alter table public.scenes
  add column status text not null default 'draft' check (status in ('draft', 'approved'));

-- 構成レビューの「通す」確定先（構成レビューの対象はプロジェクト全体のため projects に持つ）
alter table public.projects
  add column structure_status text not null default 'draft'
    check (structure_status in ('draft', 'approved'));

